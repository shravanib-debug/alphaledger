-- IDs below 1000 (portfolios, funds) and 10000 (instruments) are reserved for seeded demo and reference
-- data, whose IDs must be identical across services (prd.md §10, architecture.md §5.8).

CREATE TABLE portfolio (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH 1000) PRIMARY KEY,
    name          VARCHAR(120) NOT NULL UNIQUE,
    manager_id    BIGINT       NOT NULL,   -- auth-service user ID; no cross-service foreign key
    base_currency VARCHAR(3)   NOT NULL DEFAULT 'INR',
    status        VARCHAR(16)  NOT NULL DEFAULT 'ACTIVE' CHECK (status IN ('ACTIVE', 'ARCHIVED')),
    created_at    TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now(),
    updated_at    TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now()
);

CREATE TABLE fund (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH 1000) PRIMARY KEY,
    portfolio_id BIGINT       NOT NULL REFERENCES portfolio (id),
    name         VARCHAR(120) NOT NULL,
    asset_class  VARCHAR(20)  NOT NULL CHECK (asset_class IN ('PRIVATE_EQUITY', 'CREDIT', 'REAL_ESTATE')),
    UNIQUE (portfolio_id, name)
);

CREATE TABLE instrument (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH 10000) PRIMARY KEY,
    isin              VARCHAR(12)  NOT NULL UNIQUE,   -- primary business key; symbol is secondary
    symbol            VARCHAR(40),
    exchange          VARCHAR(10),
    name              VARCHAR(200) NOT NULL,
    asset_class       VARCHAR(20)  NOT NULL CHECK (asset_class IN ('PRIVATE_EQUITY', 'CREDIT', 'REAL_ESTATE')),
    asset_class_proxy VARCHAR(32)  NOT NULL,
    instrument_type   VARCHAR(16)  NOT NULL
        CHECK (instrument_type IN ('EQUITY', 'REIT', 'INVIT', 'GSEC', 'BOND', 'MUTUAL_FUND', 'PRIVATE')),
    currency          VARCHAR(3)   NOT NULL DEFAULT 'INR',
    amfi_scheme_code  VARCHAR(20),
    is_synthetic      BOOLEAN      NOT NULL DEFAULT FALSE,
    status            VARCHAR(16)  NOT NULL DEFAULT 'ACTIVE' CHECK (status IN ('ACTIVE', 'INACTIVE'))
);

CREATE INDEX ix_fund_portfolio ON fund (portfolio_id);
CREATE INDEX ix_instrument_asset_class ON instrument (asset_class);

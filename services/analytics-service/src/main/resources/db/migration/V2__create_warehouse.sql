    instrument_id   BIGINT       NOT NULL UNIQUE,
    isin            VARCHAR(12)  NOT NULL,
    symbol          VARCHAR(40),
    exchange        VARCHAR(10),
    name            VARCHAR(200) NOT NULL,
    instrument_type VARCHAR(16)  NOT NULL,
    asset_class     VARCHAR(20)  NOT NULL,
    currency        VARCHAR(3)   NOT NULL,
    is_synthetic    BOOLEAN      NOT NULL,
    updated_at      TIMESTAMP WITH TIME ZONE NOT NULL
);

INSERT INTO core.dim_instrument (instrument_key, instrument_id, isin, name, instrument_type, asset_class, currency,
                                 is_synthetic, updated_at)
VALUES (-1, -1, 'UNKNOWN', 'Unknown', 'UNKNOWN', 'UNKNOWN', 'INR', FALSE, now());

-- Grain: one row per trade, latest state (status changes overwrite).
CREATE TABLE core.fact_trade (
    trade_id        BIGINT PRIMARY KEY,
    date_key        INT            NOT NULL,   -- trade date
    settle_date_key INT            NOT NULL,
    portfolio_key   BIGINT         NOT NULL,
    instrument_key  BIGINT         NOT NULL,
    trade_ref       VARCHAR(40)    NOT NULL,
    side            VARCHAR(4)     NOT NULL,
    quantity        NUMERIC(20, 4) NOT NULL,
    price           NUMERIC(20, 6) NOT NULL,
    notional        NUMERIC(24, 2) NOT NULL,
    status          VARCHAR(16)    NOT NULL,
    loaded_at       TIMESTAMP WITH TIME ZONE NOT NULL
);

-- Grain: portfolio x instrument x business day (from position-service's daily snapshot, valued at the latest
-- price on or before that day).
CREATE TABLE core.fact_position_daily (
    date_key       INT            NOT NULL,
    portfolio_key  BIGINT         NOT NULL,
    instrument_key BIGINT         NOT NULL,
    quantity       NUMERIC(20, 4) NOT NULL,
    avg_cost       NUMERIC(20, 6) NOT NULL,
    cost           NUMERIC(24, 2) NOT NULL,
    price          NUMERIC(20, 6),            -- null: no price on or before the day (unpriced)
    price_date     DATE,
    market_value   NUMERIC(24, 2),
    unrealized_pnl NUMERIC(24, 2),
    realized_pnl   NUMERIC(24, 2) NOT NULL,
    loaded_at      TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE UNIQUE INDEX ux_fact_position_daily_grain ON core.fact_position_daily (date_key, portfolio_key, instrument_key);

-- Grain: portfolio x day (valuation-service's end-of-day snapshot).
CREATE TABLE core.fact_valuation_daily (
    date_key          INT            NOT NULL,
    portfolio_key     BIGINT         NOT NULL,
    market_value      NUMERIC(24, 2) NOT NULL,
    cash_balance      NUMERIC(24, 2) NOT NULL,
    total_liabilities NUMERIC(24, 2) NOT NULL,
    nav               NUMERIC(24, 2),
    valuation_basis   VARCHAR(20)    NOT NULL,
    total_cost        NUMERIC(24, 2) NOT NULL,
    realized_pnl      NUMERIC(24, 2) NOT NULL,
    unrealized_pnl    NUMERIC(24, 2) NOT NULL,
    loaded_at         TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE UNIQUE INDEX ux_fact_valuation_daily_grain ON core.fact_valuation_daily (date_key, portfolio_key);

-- Grain: one row per break, latest state.
CREATE TABLE core.fact_recon_break (
    break_id          BIGINT PRIMARY KEY,
    date_key          INT          NOT NULL,   -- day the break was raised (IST)
    resolved_date_key INT,
    portfolio_key     BIGINT       NOT NULL,
    run_id            BIGINT       NOT NULL,
    break_type        VARCHAR(20)  NOT NULL,
    status            VARCHAR(16)  NOT NULL,
    resolution_type   VARCHAR(24),
    trade_ref         VARCHAR(40)  NOT NULL,
    isin              VARCHAR(12)  NOT NULL,
    age_days          INT          NOT NULL,   -- raised -> resolved, or raised -> the load's run date if open
    loaded_at         TIMESTAMP WITH TIME ZONE NOT NULL
);

-- ---------- ETL runs and data quality ----------

CREATE TABLE core.etl_run (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_date      DATE         NOT NULL,
    full_refresh  BOOLEAN      NOT NULL,
    status        VARCHAR(10)  NOT NULL CHECK (status IN ('RUNNING', 'COMPLETED', 'FAILED')),
    rows_extracted JSONB,
    rows_loaded    JSONB,
    message       VARCHAR(1000),
    started_at    TIMESTAMP WITH TIME ZONE NOT NULL,
    finished_at   TIMESTAMP WITH TIME ZONE
);

CREATE TABLE core.dq_check_result (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    etl_run_id BIGINT        NOT NULL REFERENCES core.etl_run (id),
    check_name VARCHAR(60)   NOT NULL,
    category   VARCHAR(20)   NOT NULL CHECK (category IN ('ROW_COUNT', 'NOT_NULL', 'UNIQUENESS', 'REFERENTIAL',
                                                          'SANITY', 'FRESHNESS')),
    severity   VARCHAR(10)   NOT NULL CHECK (severity IN ('CRITICAL', 'WARNING', 'INFO')),
    status     VARCHAR(10)   NOT NULL CHECK (status IN ('PASSED', 'FAILED')),
    expected   VARCHAR(100),
    actual     VARCHAR(100),
    details    VARCHAR(1000),
    run_at     TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE INDEX ix_dq_check_result_run ON core.dq_check_result (etl_run_id);

-- ---------- Marts: business-ready views ----------

-- Assets under management (market value) by asset class and day; share of the day's total.
CREATE VIEW mart.vw_aum_by_asset_class AS
SELECT d.date, i.asset_class,
       sum(f.market_value)                                     AS market_value,
       count(*)                                                AS positions,
       round(100 * sum(f.market_value)
             / NULLIF(sum(sum(f.market_value)) OVER (PARTITION BY d.date), 0), 2) AS pct_of_total
FROM core.fact_position_daily f
JOIN core.dim_date d ON d.date_key = f.date_key
JOIN core.dim_instrument i ON i.instrument_key = f.instrument_key
WHERE f.market_value IS NOT NULL AND f.quantity <> 0
GROUP BY d.date, i.asset_class;

-- P&L per portfolio and day: realized and unrealized to date, and the day's change in total P&L.
CREATE VIEW mart.vw_daily_pnl AS
SELECT d.date, p.portfolio_id, p.name AS portfolio_name, f.market_value, f.nav, f.realized_pnl, f.unrealized_pnl,
       f.realized_pnl + f.unrealized_pnl AS total_pnl,
       f.realized_pnl + f.unrealized_pnl
           - LAG(f.realized_pnl + f.unrealized_pnl) OVER (PARTITION BY f.portfolio_key ORDER BY f.date_key)
           AS daily_pnl
FROM core.fact_valuation_daily f
JOIN core.dim_date d ON d.date_key = f.date_key
JOIN core.dim_portfolio p ON p.portfolio_key = f.portfolio_key;

-- Per day and break type: raised that day, resolved that day, and still open at the end of the day. Covers the days
-- from the first break raised to the latest one raised or resolved.
CREATE VIEW mart.vw_break_trend AS
WITH span AS (
    SELECT min(date_key) AS first_key,
           greatest(max(date_key), coalesce(max(resolved_date_key), 0)) AS last_key
    FROM core.fact_recon_break
), types AS (
    SELECT DISTINCT break_type FROM core.fact_recon_break
)
SELECT d.date, t.break_type,
       count(*) FILTER (WHERE b.date_key = d.date_key)          AS raised,
       count(*) FILTER (WHERE b.resolved_date_key = d.date_key) AS resolved,
       count(*) FILTER (WHERE b.date_key <= d.date_key
                          AND (b.resolved_date_key IS NULL OR b.resolved_date_key > d.date_key)) AS open_at_end_of_day
FROM span
JOIN core.dim_date d ON d.date_key BETWEEN span.first_key AND span.last_key
CROSS JOIN types t
LEFT JOIN core.fact_recon_break b ON b.break_type = t.break_type
GROUP BY d.date, t.break_type;

-- Breaks not yet resolved, by type and age bucket (age as of the latest load).
CREATE VIEW mart.vw_break_ageing AS
SELECT break_type,
       CASE WHEN age_days <= 1 THEN '0-1 days'
            WHEN age_days <= 3 THEN '2-3 days'
            WHEN age_days <= 7 THEN '4-7 days'
            WHEN age_days <= 14 THEN '8-14 days'
            ELSE '15+ days' END AS age_bucket,
       CASE WHEN age_days <= 1 THEN 1 WHEN age_days <= 3 THEN 2 WHEN age_days <= 7 THEN 3
            WHEN age_days <= 14 THEN 4 ELSE 5 END AS bucket_order,
       count(*) AS open_breaks,
       max(age_days) AS oldest_days
FROM core.fact_recon_break
WHERE status <> 'RESOLVED'
GROUP BY 1, 2, 3;

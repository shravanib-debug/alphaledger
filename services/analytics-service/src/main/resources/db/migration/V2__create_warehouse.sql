-- Analytics warehouse (architecture.md §5.6, §6.8): staging -> core star schema -> mart views.
-- Three schemas mirror the layers. No foreign keys between facts and dimensions, as in most warehouses: referential
-- integrity is checked by the data-quality step (dq_check_result) instead, so a bad load is reported, not hidden.

CREATE SCHEMA staging;
CREATE SCHEMA core;
CREATE SCHEMA mart;

-- ---------- Staging: exact copies of each run's source extracts (truncated at the start of every run) ----------

CREATE TABLE staging.stg_portfolio (
    portfolio_id  BIGINT       NOT NULL,
    name          VARCHAR(120) NOT NULL,
    base_currency VARCHAR(3)   NOT NULL,
    status        VARCHAR(16)  NOT NULL
);

CREATE TABLE staging.stg_instrument (
    instrument_id   BIGINT       NOT NULL,
    isin            VARCHAR(12)  NOT NULL,
    symbol          VARCHAR(40),
    exchange        VARCHAR(10),
    name            VARCHAR(200) NOT NULL,
    asset_class     VARCHAR(20)  NOT NULL,
    instrument_type VARCHAR(16)  NOT NULL,
    currency        VARCHAR(3)   NOT NULL,
    is_synthetic    BOOLEAN      NOT NULL
);

CREATE TABLE staging.stg_trade (
    trade_id      BIGINT         NOT NULL,
    trade_ref     VARCHAR(40)    NOT NULL,
    portfolio_id  BIGINT         NOT NULL,
    instrument_id BIGINT,
    isin          VARCHAR(12)    NOT NULL,
    side          VARCHAR(4)     NOT NULL,
    quantity      NUMERIC(20, 4) NOT NULL,
    price         NUMERIC(20, 6) NOT NULL,
    trade_date    DATE           NOT NULL,
    settle_date   DATE           NOT NULL,
    status        VARCHAR(16)    NOT NULL,
    updated_at    TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE TABLE staging.stg_position_snapshot (
    portfolio_id  BIGINT         NOT NULL,
    instrument_id BIGINT         NOT NULL,
    snapshot_date DATE           NOT NULL,
    quantity      NUMERIC(20, 4) NOT NULL,
    avg_cost      NUMERIC(20, 6) NOT NULL,
    realized_pnl  NUMERIC(24, 6) NOT NULL
);

-- One price per instrument and data date (the source's choice of best price that day).
CREATE TABLE staging.stg_price (
    instrument_id BIGINT         NOT NULL,
    data_date     DATE           NOT NULL,
    price         NUMERIC(20, 6) NOT NULL,
    source        VARCHAR(20)    NOT NULL
);

CREATE TABLE staging.stg_valuation_snapshot (
    portfolio_id      BIGINT         NOT NULL,
    as_of_date        DATE           NOT NULL,
    market_value      NUMERIC(24, 2) NOT NULL,
    total_cost        NUMERIC(24, 2) NOT NULL,
    unrealized_pnl    NUMERIC(24, 2) NOT NULL,
    realized_pnl      NUMERIC(24, 2) NOT NULL,
    cash_balance      NUMERIC(24, 2) NOT NULL,
    total_liabilities NUMERIC(24, 2) NOT NULL,
    nav               NUMERIC(24, 2),
    valuation_basis   VARCHAR(20)    NOT NULL
);

CREATE TABLE staging.stg_recon_break (
    break_id        BIGINT       NOT NULL,
    run_id          BIGINT       NOT NULL,
    break_type      VARCHAR(20)  NOT NULL,
    trade_ref       VARCHAR(40)  NOT NULL,
    isin            VARCHAR(12)  NOT NULL,
    portfolio_id    BIGINT,
    status          VARCHAR(16)  NOT NULL,
    resolution_type VARCHAR(24),
    created_at      TIMESTAMP WITH TIME ZONE NOT NULL,
    resolved_at     TIMESTAMP WITH TIME ZONE
);

-- ---------- Core: conformed dimensions and facts ----------

CREATE TABLE core.dim_date (
    date_key    INT         PRIMARY KEY,   -- yyyymmdd
    date        DATE        NOT NULL UNIQUE,
    day         SMALLINT    NOT NULL,
    month       SMALLINT    NOT NULL,
    month_name  VARCHAR(10) NOT NULL,
    quarter     SMALLINT    NOT NULL,
    year        SMALLINT    NOT NULL,
    day_of_week SMALLINT    NOT NULL,      -- ISO: 1 = Monday
    is_weekend  BOOLEAN     NOT NULL
);

INSERT INTO core.dim_date (date_key, date, day, month, month_name, quarter, year, day_of_week, is_weekend)
SELECT to_char(d, 'YYYYMMDD')::INT, d, extract(DAY FROM d), extract(MONTH FROM d), trim(to_char(d, 'Month')),
       extract(QUARTER FROM d), extract(YEAR FROM d), extract(ISODOW FROM d), extract(ISODOW FROM d) >= 6
FROM generate_series(DATE '2020-01-01', DATE '2035-12-31', INTERVAL '1 day') AS g(d);

-- SCD type 1 (overwritten from the source each run); key -1 is the "Unknown" member.
CREATE TABLE core.dim_portfolio (
    portfolio_key BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    portfolio_id  BIGINT       NOT NULL UNIQUE,
    name          VARCHAR(120) NOT NULL,
    base_currency VARCHAR(3)   NOT NULL,
    status        VARCHAR(16)  NOT NULL,
    updated_at    TIMESTAMP WITH TIME ZONE NOT NULL
);

INSERT INTO core.dim_portfolio (portfolio_key, portfolio_id, name, base_currency, status, updated_at)
VALUES (-1, -1, 'Unknown', 'INR', 'UNKNOWN', now());

CREATE TABLE core.dim_instrument (

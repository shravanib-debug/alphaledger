-- Server-generated trade references: TRD-<trade date yyyyMMdd>-<sequence, at least 4 digits>.
CREATE SEQUENCE trade_ref_seq START WITH 1;

CREATE TABLE trade (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    trade_ref        VARCHAR(40)    NOT NULL UNIQUE,   -- client-supplied or generated; idempotency key
    portfolio_id     BIGINT         NOT NULL,          -- portfolio-service ID (no cross-service FK)
    instrument_id    BIGINT,                           -- null only for trades rejected because the ISIN is unknown
    isin             VARCHAR(12)    NOT NULL,
    side             VARCHAR(4)     NOT NULL CHECK (side IN ('BUY', 'SELL')),
    quantity         NUMERIC(20, 4) NOT NULL CHECK (quantity > 0),
    price            NUMERIC(20, 6) NOT NULL CHECK (price > 0),
    currency         VARCHAR(3)     NOT NULL DEFAULT 'INR',
    trade_date       DATE           NOT NULL,
    settle_date      DATE           NOT NULL,
    status           VARCHAR(16)    NOT NULL
        CHECK (status IN ('NEW', 'VALIDATED', 'SETTLED', 'REJECTED', 'CANCELLED')),
    rejection_reason VARCHAR(300),
    created_by       BIGINT         NOT NULL,
    created_at       TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at       TIMESTAMP WITH TIME ZONE NOT NULL,
    version          BIGINT         NOT NULL DEFAULT 0,
    CHECK (settle_date >= trade_date)
);

CREATE INDEX ix_trade_portfolio_date ON trade (portfolio_id, trade_date);
CREATE INDEX ix_trade_holding ON trade (portfolio_id, instrument_id);
CREATE INDEX ix_trade_due_settlement ON trade (settle_date) WHERE status = 'VALIDATED';

-- Immutable history of every status change (FR-REC-9 style audit for trades).
CREATE TABLE trade_audit (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    trade_id    BIGINT      NOT NULL REFERENCES trade (id),
    from_status VARCHAR(16),
    to_status   VARCHAR(16) NOT NULL,
    changed_by  BIGINT,                 -- null for system actions (auto-settlement)
    changed_at  TIMESTAMP WITH TIME ZONE NOT NULL,
    comment     VARCHAR(500)
);

CREATE INDEX ix_trade_audit_trade ON trade_audit (trade_id);

-- Transactional outbox: written in the same transaction as the trade, published to Kafka by the relay.
CREATE TABLE outbox_event (
    id             UUID         PRIMARY KEY,
    aggregate_type VARCHAR(40)  NOT NULL,
    aggregate_id   VARCHAR(40)  NOT NULL,
    event_type     VARCHAR(60)  NOT NULL,
    topic          VARCHAR(100) NOT NULL,
    message_key    VARCHAR(100) NOT NULL,
    payload        JSONB        NOT NULL,
    status         VARCHAR(10)  NOT NULL DEFAULT 'PENDING' CHECK (status IN ('PENDING', 'SENT')),
    attempts       INT          NOT NULL DEFAULT 0,
    last_error     VARCHAR(500),
    created_at     TIMESTAMP WITH TIME ZONE NOT NULL,
    sent_at        TIMESTAMP WITH TIME ZONE
);

CREATE INDEX ix_outbox_pending ON outbox_event (created_at) WHERE status = 'PENDING';

-- Notifications (architecture.md §3, FR-NOT-*). One row per event, addressed to a role; who has read it is per user.

CREATE TABLE notification (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    type            VARCHAR(30)  NOT NULL CHECK (type IN ('RECON_BREAK', 'LIMIT_BREACH', 'OPEN_BREAKS_DIGEST')),
    severity        VARCHAR(10)  NOT NULL CHECK (severity IN ('INFO', 'WARNING', 'CRITICAL')),
    audience_role   VARCHAR(20)  NOT NULL,
    portfolio_id    BIGINT,
    reference       VARCHAR(60),             -- e.g. break ID, or portfolio:assetClass:date
    title           VARCHAR(200) NOT NULL,
    message         VARCHAR(2000) NOT NULL,
    created_at      TIMESTAMP WITH TIME ZONE NOT NULL,
    -- Email is sent after commit by a scheduled dispatcher, so a mail-server outage never fails the consumer.
    email_status    VARCHAR(10)  NOT NULL DEFAULT 'PENDING'
        CHECK (email_status IN ('PENDING', 'SENT', 'FAILED', 'SKIPPED')),
    email_attempts  INT          NOT NULL DEFAULT 0,
    email_error     VARCHAR(500),
    emailed_at      TIMESTAMP WITH TIME ZONE
);

CREATE INDEX ix_notification_role ON notification (audience_role, created_at DESC);
CREATE INDEX ix_notification_email_pending ON notification (created_at) WHERE email_status = 'PENDING';

CREATE TABLE notification_read (
    notification_id BIGINT NOT NULL REFERENCES notification (id) ON DELETE CASCADE,
    user_id         BIGINT NOT NULL,
    read_at         TIMESTAMP WITH TIME ZONE NOT NULL,
    PRIMARY KEY (notification_id, user_id)
);

-- Breaks still open, kept from recon.break.created / recon.break.resolved, for the daily digest.
CREATE TABLE open_break (
    break_id     BIGINT PRIMARY KEY,
    run_id       BIGINT       NOT NULL,
    break_type   VARCHAR(30)  NOT NULL,
    trade_ref    VARCHAR(60),
    isin         VARCHAR(12),
    portfolio_id BIGINT,
    opened_at    TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE TABLE processed_event (
    event_id     UUID PRIMARY KEY,
    processed_at TIMESTAMP WITH TIME ZONE NOT NULL
);

-- Every trade this service has received, from trade.created and trade.cancelled. Positions are rebuilt from these
-- rows, so a cancel is reversed exactly even after later trades, and a redelivered event changes nothing.
CREATE TABLE applied_trade (
    trade_id      BIGINT         PRIMARY KEY,
    trade_ref     VARCHAR(40)    NOT NULL,
    portfolio_id  BIGINT         NOT NULL,
    instrument_id BIGINT         NOT NULL,
    isin          VARCHAR(12)    NOT NULL,
    side          VARCHAR(4)     NOT NULL CHECK (side IN ('BUY', 'SELL')),
    quantity      NUMERIC(20, 4) NOT NULL,
    price         NUMERIC(20, 6) NOT NULL,
    trade_date    DATE           NOT NULL,
    cancelled     BOOLEAN        NOT NULL DEFAULT FALSE,
    received_at   TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE INDEX ix_applied_trade_holding ON applied_trade (portfolio_id, instrument_id);

CREATE TABLE position (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    portfolio_id  BIGINT         NOT NULL,
    instrument_id BIGINT         NOT NULL,
    isin          VARCHAR(12)    NOT NULL,
    quantity      NUMERIC(20, 4) NOT NULL,
    avg_cost      NUMERIC(20, 6) NOT NULL,
    realized_pnl  NUMERIC(24, 6) NOT NULL,
    last_trade_id BIGINT,
    updated_at    TIMESTAMP WITH TIME ZONE NOT NULL,
    UNIQUE (portfolio_id, instrument_id)
);

CREATE TABLE position_snapshot (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    portfolio_id  BIGINT         NOT NULL,
    instrument_id BIGINT         NOT NULL,
    isin          VARCHAR(12)    NOT NULL,
    snapshot_date DATE           NOT NULL,
    quantity      NUMERIC(20, 4) NOT NULL,
    avg_cost      NUMERIC(20, 6) NOT NULL,
    realized_pnl  NUMERIC(24, 6) NOT NULL,
    UNIQUE (portfolio_id, instrument_id, snapshot_date)
);

-- Trades that could not be applied (a SELL above the holding). trade-service rejects these first; this is the
-- second line of defence and makes any such case visible instead of silently producing a negative holding.
CREATE TABLE position_exception (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    trade_id      BIGINT       NOT NULL,
    portfolio_id  BIGINT       NOT NULL,
    instrument_id BIGINT       NOT NULL,
    reason        VARCHAR(300) NOT NULL,
    created_at    TIMESTAMP WITH TIME ZONE NOT NULL,
    UNIQUE (trade_id, reason)
);

CREATE TABLE processed_event (
    event_id     UUID PRIMARY KEY,
    processed_at TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE TABLE holiday_calendar (
    holiday_date DATE         NOT NULL,
    exchange     VARCHAR(10)  NOT NULL DEFAULT 'NSE',
    segment      VARCHAR(10)  NOT NULL DEFAULT 'CM',
    description  VARCHAR(200) NOT NULL,
    PRIMARY KEY (holiday_date, exchange, segment)
);

CREATE TABLE outbox_event (
    id             UUID         PRIMARY KEY,
    aggregate_type VARCHAR(40)  NOT NULL,
    aggregate_id   VARCHAR(40)  NOT NULL,
    event_type     VARCHAR(60)  NOT NULL,
    topic          VARCHAR(100) NOT NULL,
    message_key    VARCHAR(100) NOT NULL,
    payload        JSONB        NOT NULL,
    status         VARCHAR(10)  NOT NULL DEFAULT 'PENDING' CHECK (status IN ('PENDING', 'SENT')),
    attempts       INT          NOT NULL DEFAULT 0,
    last_error     VARCHAR(500),
    created_at     TIMESTAMP WITH TIME ZONE NOT NULL,
    sent_at        TIMESTAMP WITH TIME ZONE
);

CREATE INDEX ix_outbox_pending ON outbox_event (created_at) WHERE status = 'PENDING';

-- Valuation (architecture.md §5.4, §5.4a, §6.5). v1 reports Market Value only; NAV columns stay empty until v1.5.

-- valuation-service's copy of holdings, replaced from each position.updated event (full state, last write wins).
CREATE TABLE position_view (
    portfolio_id  BIGINT         NOT NULL,
    instrument_id BIGINT         NOT NULL,
    isin          VARCHAR(12)    NOT NULL,
    quantity      NUMERIC(20, 4) NOT NULL,
    avg_cost      NUMERIC(20, 6) NOT NULL,
    realized_pnl  NUMERIC(24, 6) NOT NULL,
    last_trade_id BIGINT         NOT NULL,
    updated_at    TIMESTAMP WITH TIME ZONE NOT NULL,
    PRIMARY KEY (portfolio_id, instrument_id)
);

CREATE TABLE valuation_snapshot (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    portfolio_id       BIGINT         NOT NULL,
    as_of_date         DATE           NOT NULL,
    market_value       NUMERIC(24, 2) NOT NULL,
    total_cost         NUMERIC(24, 2) NOT NULL,
    unrealized_pnl     NUMERIC(24, 2) NOT NULL,
    realized_pnl       NUMERIC(24, 2) NOT NULL,
    cash_balance       NUMERIC(24, 2) NOT NULL DEFAULT 0,   -- v1.5
    total_liabilities  NUMERIC(24, 2) NOT NULL DEFAULT 0,   -- v1.5
    nav                NUMERIC(24, 2),                      -- NULL until v1.5: market value is not NAV
    valuation_basis    VARCHAR(20)    NOT NULL DEFAULT 'MARKET_VALUE_ONLY'
        CHECK (valuation_basis IN ('MARKET_VALUE_ONLY', 'FULL_NAV')),
    priced_positions   INT            NOT NULL,
    stale_positions    INT            NOT NULL,
    unpriced_positions INT            NOT NULL,
    created_at         TIMESTAMP WITH TIME ZONE NOT NULL,
    UNIQUE (portfolio_id, as_of_date)
);

CREATE TABLE exposure_snapshot (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    portfolio_id BIGINT         NOT NULL,
    as_of_date   DATE           NOT NULL,
    asset_class  VARCHAR(20)    NOT NULL,
    market_value NUMERIC(24, 2) NOT NULL,
    pct_of_total NUMERIC(7, 2)  NOT NULL,   -- share of portfolio market value
    UNIQUE (portfolio_id, as_of_date, asset_class)
);

-- Maximum share of market value per asset class; portfolio_id NULL means "every portfolio" (FR-VAL-7).
CREATE TABLE limit_rule (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    portfolio_id BIGINT,
    asset_class  VARCHAR(20)   NOT NULL CHECK (asset_class IN ('PRIVATE_EQUITY', 'CREDIT', 'REAL_ESTATE')),
    max_pct      NUMERIC(5, 2) NOT NULL CHECK (max_pct > 0 AND max_pct <= 100),
    UNIQUE NULLS NOT DISTINCT (portfolio_id, asset_class)
);

-- One breach per portfolio, asset class and day, so limit.breached is published once.
CREATE TABLE limit_breach (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    portfolio_id BIGINT         NOT NULL,
    asset_class  VARCHAR(20)    NOT NULL,
    as_of_date   DATE           NOT NULL,
    exposure_pct NUMERIC(7, 2)  NOT NULL,
    max_pct      NUMERIC(5, 2)  NOT NULL,
    market_value NUMERIC(24, 2) NOT NULL,
    created_at   TIMESTAMP WITH TIME ZONE NOT NULL,
    UNIQUE (portfolio_id, asset_class, as_of_date)
);

CREATE TABLE processed_event (
    event_id     UUID PRIMARY KEY,
    processed_at TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE TABLE outbox_event (
    id             UUID         PRIMARY KEY,
    aggregate_type VARCHAR(40)  NOT NULL,
    aggregate_id   VARCHAR(40)  NOT NULL,
    event_type     VARCHAR(60)  NOT NULL,
    topic          VARCHAR(100) NOT NULL,
    message_key    VARCHAR(100) NOT NULL,
    payload        JSONB        NOT NULL,
    status         VARCHAR(10)  NOT NULL DEFAULT 'PENDING' CHECK (status IN ('PENDING', 'SENT')),
    attempts       INT          NOT NULL DEFAULT 0,
    last_error     VARCHAR(500),
    created_at     TIMESTAMP WITH TIME ZONE NOT NULL,
    sent_at        TIMESTAMP WITH TIME ZONE
);

CREATE INDEX ix_outbox_pending ON outbox_event (created_at) WHERE status = 'PENDING';

-- Market data (architecture.md §5.3, §5.8, §6.5).

-- Read copy of portfolio-service instruments, seeded from the same instrument master with the same IDs.
CREATE TABLE instrument_ref (
    instrument_id     BIGINT       PRIMARY KEY,
    isin              VARCHAR(12)  NOT NULL UNIQUE,
    symbol            VARCHAR(40),
    exchange          VARCHAR(10),
    name              VARCHAR(200) NOT NULL,
    instrument_type   VARCHAR(16)  NOT NULL,
    asset_class       VARCHAR(20)  NOT NULL,
    asset_class_proxy VARCHAR(32)  NOT NULL,
    amfi_scheme_code  VARCHAR(20),
    is_synthetic      BOOLEAN      NOT NULL
);

CREATE TABLE holiday_calendar (
    holiday_date DATE         NOT NULL,
    exchange     VARCHAR(10)  NOT NULL DEFAULT 'NSE',
    segment      VARCHAR(10)  NOT NULL DEFAULT 'CM',
    description  VARCHAR(200) NOT NULL,
    PRIMARY KEY (holiday_date, exchange, segment)
);

-- One row per ingestion attempt. A file (by checksum) is loaded at most once per source: later attempts are logged
-- as SKIPPED_DUPLICATE, hence the partial unique index rather than a plain unique constraint.
CREATE TABLE price_ingestion_log (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source        VARCHAR(20)  NOT NULL,
    data_date     DATE,
    file_name     VARCHAR(200),
    file_checksum VARCHAR(64)  NOT NULL,
    rows_read     INT          NOT NULL DEFAULT 0,
    rows_loaded   INT          NOT NULL DEFAULT 0,
    rows_rejected INT          NOT NULL DEFAULT 0,
    status        VARCHAR(20)  NOT NULL
        CHECK (status IN ('RUNNING', 'SUCCESS', 'PARTIAL', 'FAILED', 'SKIPPED_DUPLICATE')),
    error_message VARCHAR(500),
    started_at    TIMESTAMP WITH TIME ZONE NOT NULL,
    completed_at  TIMESTAMP WITH TIME ZONE
);

CREATE UNIQUE INDEX ux_ingestion_loaded_once ON price_ingestion_log (source, file_checksum)
    WHERE status IN ('SUCCESS', 'PARTIAL');

CREATE TABLE price_ingestion_error (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ingestion_id BIGINT       NOT NULL REFERENCES price_ingestion_log (id),
    row_number   INT,
    isin         VARCHAR(12),
    reason       VARCHAR(300) NOT NULL,
    raw_row      VARCHAR(1000)
);

CREATE INDEX ix_ingestion_error_ingestion ON price_ingestion_error (ingestion_id);

CREATE TABLE price (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    instrument_id    BIGINT         NOT NULL REFERENCES instrument_ref (instrument_id),
    isin             VARCHAR(12)    NOT NULL,
    price            NUMERIC(20, 6) NOT NULL CHECK (price > 0),
    currency         VARCHAR(3)     NOT NULL DEFAULT 'INR',
    data_date        DATE           NOT NULL,   -- the date the source says the price is for
    as_of_timestamp  TIMESTAMP WITH TIME ZONE NOT NULL,
    source           VARCHAR(20)    NOT NULL
        CHECK (source IN ('NSE_BHAVCOPY', 'AMFI_NAV', 'MFAPI', 'SYNTHETIC', 'CSV_UPLOAD', 'YFINANCE')),
    fair_value_level VARCHAR(2),               -- L3 for synthetic model marks (FR-VAL-12)
    ingestion_id     BIGINT REFERENCES price_ingestion_log (id)
);

-- Real sources: one end-of-day price per instrument, date and source. SYNTHETIC: one per timestamp (ticks, marks).
CREATE UNIQUE INDEX ux_price_real ON price (instrument_id, data_date, source) WHERE source <> 'SYNTHETIC';
CREATE UNIQUE INDEX ux_price_synthetic ON price (instrument_id, as_of_timestamp, source) WHERE source = 'SYNTHETIC';
CREATE INDEX ix_price_latest ON price (instrument_id, data_date DESC, as_of_timestamp DESC);

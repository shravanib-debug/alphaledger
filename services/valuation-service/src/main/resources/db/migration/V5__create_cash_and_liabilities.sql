-- Cash and liabilities for full NAV (v1.5; architecture.md §5.4a, §8). NAV = market value + cash - liabilities.

-- Append-only ledger: rows are never updated or deleted. Amounts are signed (in > 0, out < 0), in INR.
-- effective_date is when the cash moves (settle date for trades), so a past date's cash can be rebuilt.
CREATE TABLE cash_transaction (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    portfolio_id   BIGINT         NOT NULL,
    type           VARCHAR(20)    NOT NULL
        CHECK (type IN ('DEPOSIT', 'WITHDRAWAL', 'TRADE_BUY', 'TRADE_SELL', 'LIABILITY_PAYMENT', 'BORROWING')),
    amount         NUMERIC(24, 2) NOT NULL CHECK (amount <> 0),
    currency       VARCHAR(3)     NOT NULL DEFAULT 'INR',
    reference_id   VARCHAR(60),
    description    VARCHAR(200),
    effective_date DATE           NOT NULL,
    occurred_at    TIMESTAMP WITH TIME ZONE NOT NULL,
    created_by     BIGINT
);

CREATE INDEX ix_cash_transaction_portfolio ON cash_transaction (portfolio_id, effective_date);
-- A trade settles once, even if trade.settled is redelivered with a new event ID.
CREATE UNIQUE INDEX ux_cash_transaction_trade ON cash_transaction (type, reference_id)
    WHERE type IN ('TRADE_BUY', 'TRADE_SELL');

CREATE FUNCTION cash_transaction_append_only() RETURNS trigger AS $$
BEGIN
    RAISE EXCEPTION 'cash_transaction is append-only';
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_cash_transaction_append_only BEFORE UPDATE OR DELETE ON cash_transaction
    FOR EACH ROW EXECUTE FUNCTION cash_transaction_append_only();

-- Current balance, derived from the ledger in the same transaction as each entry.
CREATE TABLE cash_balance (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    portfolio_id BIGINT         NOT NULL,
    currency     VARCHAR(3)     NOT NULL DEFAULT 'INR',
    balance      NUMERIC(24, 2) NOT NULL,
    updated_at   TIMESTAMP WITH TIME ZONE NOT NULL,
    UNIQUE (portfolio_id, currency)
);

-- A liability counts towards NAV from accrual_date until it is paid (paid_date) or deleted.
CREATE TABLE liability (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    portfolio_id BIGINT         NOT NULL,
    type         VARCHAR(20)    NOT NULL CHECK (type IN ('MANAGEMENT_FEE', 'EXPENSE', 'PAYABLE', 'BORROWING')),
    description  VARCHAR(200)   NOT NULL,
    amount       NUMERIC(24, 2) NOT NULL CHECK (amount > 0),
    accrual_date DATE           NOT NULL,
    status       VARCHAR(10)    NOT NULL DEFAULT 'OPEN' CHECK (status IN ('OPEN', 'PAID')),
    paid_date    DATE,
    created_at   TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at   TIMESTAMP WITH TIME ZONE NOT NULL,
    CHECK ((status = 'PAID') = (paid_date IS NOT NULL))
);

CREATE INDEX ix_liability_portfolio ON liability (portfolio_id, accrual_date);
-- The daily fee accrual writes one row per portfolio and day.
CREATE UNIQUE INDEX ux_liability_fee_accrual ON liability (portfolio_id, accrual_date) WHERE type = 'MANAGEMENT_FEE';

-- Reconciliation (architecture.md §5.5, §6.6). All amounts in INR.

-- Settled trades, copied from trade.settled: the internal side of every match.
CREATE TABLE settled_trade_view (
    trade_id      BIGINT         PRIMARY KEY,
    trade_ref     VARCHAR(40)    NOT NULL,
    portfolio_id  BIGINT         NOT NULL,
    instrument_id BIGINT         NOT NULL,
    isin          VARCHAR(12)    NOT NULL,
    side          VARCHAR(4)     NOT NULL,
    quantity      NUMERIC(20, 4) NOT NULL,
    price         NUMERIC(20, 6) NOT NULL,
    trade_date    DATE           NOT NULL,
    settle_date   DATE           NOT NULL,
    received_at   TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE INDEX ix_settled_trade_settle_date ON settled_trade_view (settle_date);

-- One run per uploaded custodian file. The same file (checksum) for the same date and source is never run twice.
CREATE TABLE recon_run (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_date         DATE         NOT NULL,   -- the settlement date the custodian file covers
    source           VARCHAR(40)  NOT NULL,   -- custodian name
    file_name        VARCHAR(200),
    file_checksum    VARCHAR(64)  NOT NULL,
    status           VARCHAR(16)  NOT NULL CHECK (status IN ('RUNNING', 'COMPLETED', 'FAILED')),
    total_records    INT          NOT NULL DEFAULT 0,
    error_rows       INT          NOT NULL DEFAULT 0,
    internal_trades  INT          NOT NULL DEFAULT 0,
    matched_count    INT          NOT NULL DEFAULT 0,
    break_count      INT          NOT NULL DEFAULT 0,
    missing_internal INT          NOT NULL DEFAULT 0,
    missing_external INT          NOT NULL DEFAULT 0,
    qty_mismatch     INT          NOT NULL DEFAULT 0,
    price_mismatch   INT          NOT NULL DEFAULT 0,
    created_by       BIGINT,
    started_at       TIMESTAMP WITH TIME ZONE NOT NULL,
    completed_at     TIMESTAMP WITH TIME ZONE,
    error_message    VARCHAR(500),
    UNIQUE (run_date, source, file_checksum)
);

-- The raw file, kept for audit and so the batch job reads exactly what was uploaded.
CREATE TABLE custodian_file (
    run_id  BIGINT PRIMARY KEY REFERENCES recon_run (id),
    content BYTEA  NOT NULL
);

CREATE TABLE custodian_record (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_id      BIGINT         NOT NULL REFERENCES recon_run (id),
    row_number  INT            NOT NULL,
    trade_ref   VARCHAR(40)    NOT NULL,
    isin        VARCHAR(12)    NOT NULL,
    trade_date  DATE           NOT NULL,
    settle_date DATE           NOT NULL,
    side        VARCHAR(4)     NOT NULL,
    quantity    NUMERIC(20, 4) NOT NULL,
    price       NUMERIC(20, 6) NOT NULL,
    raw_row     VARCHAR(1000)
);

CREATE INDEX ix_custodian_record_run ON custodian_record (run_id);

CREATE TABLE custodian_record_error (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_id        BIGINT       NOT NULL REFERENCES recon_run (id),
    row_number    INT          NOT NULL,
    error_message VARCHAR(500) NOT NULL,
    raw_row       VARCHAR(1000)
);

CREATE TABLE recon_break (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_id             BIGINT       NOT NULL REFERENCES recon_run (id),
    break_type         VARCHAR(20)  NOT NULL
        CHECK (break_type IN ('MISSING_INTERNAL', 'MISSING_EXTERNAL', 'QTY_MISMATCH', 'PRICE_MISMATCH')),
    trade_ref          VARCHAR(40)  NOT NULL,
    isin               VARCHAR(12)  NOT NULL,
    trade_date         DATE         NOT NULL,
    portfolio_id       BIGINT,                 -- known when the internal trade exists
    internal_trade_id  BIGINT,
    internal_qty       NUMERIC(20, 4),
    external_qty       NUMERIC(20, 4),
    internal_price     NUMERIC(20, 6),
    external_price     NUMERIC(20, 6),
    status             VARCHAR(16)  NOT NULL CHECK (status IN ('OPEN', 'IN_REVIEW', 'RESOLVED', 'ESCALATED')),
    assigned_to        BIGINT,
    resolution_type    VARCHAR(24)
        CHECK (resolution_type IN ('ACCEPT_EXTERNAL', 'ADJUST_INTERNAL', 'KNOWN_DIFFERENCE')),
    resolution_comment VARCHAR(500),
    created_at         TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at         TIMESTAMP WITH TIME ZONE NOT NULL,
    resolved_at        TIMESTAMP WITH TIME ZONE,
    version            BIGINT       NOT NULL DEFAULT 0
);

CREATE INDEX ix_recon_break_run ON recon_break (run_id);
CREATE INDEX ix_recon_break_status ON recon_break (status);

-- Immutable trail of every action on a break (FR-REC-9): who, what, when, before and after.
CREATE TABLE break_action_audit (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    break_id     BIGINT       NOT NULL REFERENCES recon_break (id),
    action       VARCHAR(24)  NOT NULL,
    performed_by BIGINT,
    comment      VARCHAR(500),
    before_state JSONB,
    after_state  JSONB        NOT NULL,
    performed_at TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE INDEX ix_break_audit_break ON break_action_audit (break_id);

CREATE TABLE processed_event (
    event_id     UUID PRIMARY KEY,
    processed_at TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE TABLE outbox_event (
    id             UUID         PRIMARY KEY,
    aggregate_type VARCHAR(40)  NOT NULL,
    aggregate_id   VARCHAR(40)  NOT NULL,
    event_type     VARCHAR(60)  NOT NULL,
    topic          VARCHAR(100) NOT NULL,
    message_key    VARCHAR(100) NOT NULL,
    payload        JSONB        NOT NULL,
    status         VARCHAR(10)  NOT NULL DEFAULT 'PENDING' CHECK (status IN ('PENDING', 'SENT')),
    attempts       INT          NOT NULL DEFAULT 0,
    last_error     VARCHAR(500),
    created_at     TIMESTAMP WITH TIME ZONE NOT NULL,
    sent_at        TIMESTAMP WITH TIME ZONE
);

CREATE INDEX ix_outbox_pending ON outbox_event (created_at) WHERE status = 'PENDING';
